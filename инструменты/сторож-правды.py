def главное():
    р = argparse.ArgumentParser(add_help=True)
    р.add_argument("--сделки", required=True)
    р.add_argument("--ряд")
    р.add_argument("--карта")
    р.add_argument("--спредов", type=float, default=1.0)
    р.add_argument("--допуск", type=float, default=0.0)
    р.add_argument("--сутки-брокера", dest="сутки_брокера")
    р.add_argument("--шаг-лота", dest="шаг_лота", type=float)
    р.add_argument("--мин-лот", dest="мин_лот", type=float)
    р.add_argument("--мин-стоп", dest="мин_стоп", type=float)
    р.add_argument("--точка", type=float,
                   help="размер пункта, если спред в ряду записан пунктами")
    р.add_argument("--примеров", type=int, default=3)
    а = р.parse_args()

    карта = {}
    if а.карта:
        карта = json.load(open(а.карта, encoding="utf-8"))

    print("СТОРОЖ ПРАВДЫ — проверка боевой исполнимости выгрузки\n")
    print("Сделки: %s" % os.path.basename(а.сделки))

    заголовки, сделки = читать(а.сделки)
    с = найти_столбцы(заголовки, ИМЕНА, карта.get("сделки", карта))
    # Первоначального стопа в выгрузке может не быть вовсе — тогда за него идёт
    # текущий, и это честнее, чем пропустить проверку сторон целиком.
    if not с["стоп"] and с["стоп_текущий"]:
        с["стоп"] = с["стоп_текущий"]
        print("Первоначального стопа в выгрузке нет — взят текущий "
              "(«%s»): проверки сторон идут по нему." % с["стоп"])
    нашлись = [к for к, v in с.items() if v]
    print("Столбцы узнаны: %s" % (", ".join(нашлись) if нашлись else "ни одного"))

    сутки = None
    if а.сутки_брокера:
        if а.сутки_брокера.strip().lower() == "eet-us":
            сутки = lambda ts: (ts + сдвиг_еет_сша(ts) * 3600) // 86400
        else:
            ч = float(а.сутки_брокера)
            сутки = lambda ts: int(ts + ч * 3600) // 86400

    дов = {"допуск": а.допуск, "спредов": а.спредов, "сутки": сутки,
           "шаг_лота": а.шаг_лота, "мин_лот": а.мин_лот, "мин_стоп": а.мин_стоп}

    итог = Итог(а.примеров)
    ряд = None
    if а.ряд:
        print("Ряд: %s" % os.path.basename(а.ряд))
        ряд = Ряд(а.ряд, карта.get("ряд", {}), а.точка)
        проверить_ряд(ряд, итог)
    else:
        итог.пробел("ряд котировок", "ряд не задан — цены и дыры не проверить")

    проверить_сделки(сделки, с, ряд, дов, итог)

    print()
    if итог.пробелы:
        print("НЕ ПРОВЕРЕНО — %d, это пробелы знания, а не «всё хорошо»:"
              % len(итог.пробелы))
        for имя, почему in итог.пробелы:
            print("  · %s — %s" % (имя, почему))
        print()
    if итог.бед:
        print("БЕД: %d — счёт расходится с боем. Чинить движок, а не объяснять."
              % len(итог.бед))
        return 1
    print("Бед нет. Это не значит «числа верны»: сторож проверяет только то, что "
          "верно у любого брокера.")
    return 0


if __name__ == "__main__":
    sys.exit(главное())
