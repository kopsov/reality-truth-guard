def проверить_ряд(ряд, итог):
    print("\nРяд котировок (%d баров, шаг %s с):" % (len(ряд), ряд.шаг))
    if not len(ряд):
        итог.проверка("ряд прочитан", False, "ни одного бара")
        return

    пары = list(zip(ряд.метки, ряд.метки[1:]))
    назад = [(a, b) for a, b in пары if b <= a]
    итог.проверка("метки строго растут, дублей нет", not назад,
                  "" if not назад else "случаев %d" % len(назад),
                  ["%s → %s" % (сказать_время(a), сказать_время(b)) for a, b in назад])

    битые = []
    for i in range(len(ряд)):
        в, н, о, з = ряд.верх[i], ряд.низ[i], ряд.откр[i], ряд.закр[i]
        if None in (в, н, о, з):
            continue
        if в < н or в < max(о, з) - 1e-9 or н > min(о, з) + 1e-9:
            битые.append(i)
    итог.проверка("свечи целы: верх не ниже тела, низ не выше", not битые,
                  "" if not битые else "битых свечей %d" % len(битые),
                  [сказать_время(ряд.метки[i]) for i in битые])

    if ряд.шаг:
        # Перепись перерывов. Сторож их НЕ судит: у минутного ряда бар не
        # рождается там, где не было тиков, и короткий пропуск в тихий час —
        # обычное дело, а длинный может оказаться и праздником, и настоящей
        # дырой. Судит человек, и его вывод записывается в проект (П02).
        # Дело сторожа — показать, что именно надо разобрать, и не дать
        # молчаливо проехать целым торговым суткам.
        перерывы = [(a, b - a) for a, b in пары if b - a > ряд.шаг]
        короткие = [п for п in перерывы if п[1] < 55 * 60]
        средние = [п for п in перерывы if 55 * 60 <= п[1] <= 12 * 3600]
        длинные = [п for п in перерывы if п[1] > 12 * 3600]
        print("             перерывов всего %d: короче 55 мин — %d, от 55 мин до "
              "12 ч — %d, длиннее 12 ч — %d"
              % (len(перерывы), len(короткие), len(средние), len(длинные)))

        # Обычный день недели выходных — тот, с которого начинается больше
        # всего длинных перерывов. Всё прочее длинное подозрительно: так
        # выглядит потерянный торговый день.
        if длинные:
            дни = Counter(datetime.fromtimestamp(a, timezone.utc).weekday()
                          for a, _ in длинные)
            обычный = дни.most_common(1)[0][0]
            чужие = [(a, d) for a, d in длинные
                     if datetime.fromtimestamp(a, timezone.utc).weekday() != обычный]
            if чужие:
                итог.пробел(
                    "длинные перерывы не в обычный день",
                    "их %d — разобрать каждый и записать, праздник это или дыра: %s"
                    % (len(чужие), "; ".join("%s (%.0f ч)" % (сказать_время(a), d / 3600.0)
                                             for a, d in чужие[:8])))
        if короткие:
            итог.пробел("короткие пропуски внутри сессии",
                        "их %d — у минутного ряда бар не рождается без тиков, но "
                        "разобрать один раз и записать вывод надо" % len(короткие))

    if ряд.есть_спред:
        есть = [s for s in ряд.спред if s is not None]
        нулей = sum(1 for s in есть if s <= 0)
        итог.проверка("спред в ряду живой", bool(есть) and нулей * 20 < len(есть),
                      "баров со спредом %d из %d, нулевых %d, средний %.4f"
                      % (len(есть), len(ряд), нулей,
                         sum(есть) / len(есть) if есть else 0.0))
    elif ряд.спред_в_пунктах:
        итог.пробел("спред в ряду",
                    "он записан пунктами, а не ценой: назвать размер пункта "
                    "ключом --точка, иначе допуск по спреду пропустит любую цену")
    else:
        итог.пробел("спред в ряду", "столбца спреда нет — правило П05 не проверить")


def проверить_сделки(сделки, с, ряд, дов, итог):
    print("\nСделки (%d):" % len(сделки))
    зн = lambda r, к: r.get(с[к]) if с.get(к) else None

    # --- 1. Исполнение не раньше и не в минуту своего сигнала (П17) ---------
    if с["метка_сигнала"] and с["метка_входа"]:
        влёт, раньше = [], []
        for r in сделки:
            сиг, вх = метка(зн(r, "метка_сигнала")), метка(зн(r, "метка_входа"))
            if сиг is None or вх is None:
                continue
            if вх == сиг:
                влёт.append(сиг)
            elif вх < сиг:
                раньше.append((сиг, вх))
        итог.проверка("заявка не исполняется в минуту своего сигнала", not влёт,
                      "" if not влёт else "таких сделок %d" % len(влёт),
                      [сказать_время(t) for t in влёт])
        итог.проверка("исполнение не раньше сигнала", not раньше,
                      "" if not раньше else "таких сделок %d" % len(раньше),
                      ["сигнал %s, вход %s" % (сказать_время(a), сказать_время(b))
                       for a, b in раньше])
    else:
        чего = "сигнала" if not с["метка_сигнала"] else "входа"
        итог.пробел("момент исполнения",
                    "в выгрузке нет метки %s — П17 не проверить. Это не мелочь: "
                    "без неё не видно, не взят ли вход задним числом" % чего)

    # --- 2. Отложенный ордер не переживает сутки сервера (П18) --------------
    if дов["сутки"] and с["метка_сигнала"] and с["метка_входа"]:
        долго = []
        for r in сделки:
            сиг, вх = метка(зн(r, "метка_сигнала")), метка(зн(r, "метка_входа"))
            вид = (str(зн(r, "вид") or "")).upper()
            if сиг is None or вх is None or "LIMIT" not in вид and "STOP" not in вид \
                    and "ОТЛОЖ" not in вид:
                continue
            if дов["сутки"](вх) != дов["сутки"](сиг):
                долго.append((сиг, вх))
        итог.проверка("отложенный ордер не переживает сутки брокера", not долго,
                      "" if not долго else "таких сделок %d" % len(долго),
                      ["сигнал %s, вход %s" % (сказать_время(a), сказать_время(b))
                       for a, b in долго])
    elif not дов["сутки"]:
        итог.пробел("сутки брокера",
                    "не задан ключ --сутки-брокера — П18 не проверить")
    else:
        итог.пробел("сутки брокера",
                    "нет меток сигнала и входа разом — П18 не проверить")

    # --- 3. Стоп и цель по правильные стороны от входа (П19) ----------------
    if с["вход"] and с["стоп"] and с["сторона"]:
        кривые_стоп, кривые_цель = [], []
        for r in сделки:
            лонг = сторона_лонг(зн(r, "сторона"))
            вх, ст = число(зн(r, "вход")), число(зн(r, "стоп"))
            це = число(зн(r, "цель")) if с["цель"] else None
            if лонг is None or вх is None or ст is None:
                continue
            if abs(ст - вх) > 1e-9 and ((ст > вх) if лонг else (ст < вх)):
                кривые_стоп.append((вх, ст))
            if це is not None and abs(це - вх) > 1e-9 and ((це < вх) if лонг else (це > вх)):
                кривые_цель.append((вх, це))
        итог.проверка("стоп по ту сторону входа, где его примет брокер", not кривые_стоп,
                      "" if not кривые_стоп else "таких сделок %d" % len(кривые_стоп),
                      ["вход %.5f, стоп %.5f" % (a, b) for a, b in кривые_стоп])
        итог.проверка("цель по ту сторону входа, где её примет брокер", not кривые_цель,
                      "" if not кривые_цель else "таких сделок %d (перенос цели в цену "
                      "входа сюда не считается)" % len(кривые_цель),
                      ["вход %.5f, цель %.5f" % (a, b) for a, b in кривые_цель])
    else:
        итог.пробел("стороны заявки", "нет входа, стопа или стороны — П19 не проверить")

    # --- 4. Минимальная дистанция стопа у брокера (П23) ---------------------
    if дов["мин_стоп"] and с["вход"] and с["стоп"]:
        коротких = []
        for r in сделки:
            вх, ст = число(зн(r, "вход")), число(зн(r, "стоп"))
            if вх is None or ст is None:
                continue
            if abs(вх - ст) < дов["мин_стоп"] - 1e-9:
                коротких.append(abs(вх - ст))
        итог.проверка("стоп не ближе наименьшей дистанции брокера", not коротких,
                      "" if not коротких else "таких сделок %d, самый короткий %.5f"
                      % (len(коротких), min(коротких)))
    else:
        итог.пробел("наименьшая дистанция стопа",
                    "не задан ключ --мин-стоп — П23 не проверить")

    # --- 5. Выход не раньше входа ------------------------------------------
    if с["метка_входа"] and с["метка_выхода"]:
        задом = []
        for r in сделки:
            вх, вых = метка(зн(r, "метка_входа")), метка(зн(r, "метка_выхода"))
            if вх is None or вых is None:
                continue
            if вых < вх:
                задом.append((вх, вых))
        итог.проверка("выход не раньше входа", not задом,
                      "" if not задом else "таких сделок %d" % len(задом),
                      ["вход %s, выход %s" % (сказать_время(a), сказать_время(b))
                       for a, b in задом])

    # --- 6. Цена входа существовала (П20) ----------------------------------
    if ряд and с["метка_входа"] and с["вход"]:
        мимо, вне_ряда = [], 0
        for r in сделки:
            t, ц = метка(зн(r, "метка_входа")), число(зн(r, "вход"))
            лонг = сторона_лонг(зн(r, "сторона")) if с["сторона"] else None
            if t is None or ц is None:
                continue
            i = ряд.бар(t)
            if i is None:
                вне_ряда += 1
                continue
            в, н = ряд.верх[i], ряд.низ[i]
            if в is None or н is None:
                continue
            сп = (ряд.спред[i] or 0.0) if ряд.есть_спред else 0.0
            доп = max(дов["допуск"], сп * дов["спредов"])
            выше, ниже = ц - в, н - ц
            # Лонг входит по цене покупателя и законно стоит выше верха бара на
            # спред; шорт входит по цене продавца и законно стоит ниже низа.
            # Сторона неизвестна — допуск даётся в обе стороны.
            предел_вверх = доп if лонг is not False else дов["допуск"]
            предел_вниз = доп if лонг is not True else дов["допуск"]
            if выше > предел_вверх + 1e-9 or ниже > предел_вниз + 1e-9:
                мимо.append((t, ц, н, в, доп))
        итог.проверка("цена входа лежит внутри своего бара", not мимо,
                      "" if not мимо else "таких сделок %d" % len(мимо),
                      ["%s: вход %.5f при баре %.5f–%.5f, допуск %.5f"
                       % (сказать_время(t), ц, н, в, д) for t, ц, н, в, д in мимо])
        if вне_ряда:
            итог.пробел("бар входа найден",
                        "%d сделок не нашли своего бара в ряду" % вне_ряда)

    # --- 7. Цена выхода существовала ---------------------------------------
    if ряд and с["метка_выхода"] and с["выход"]:
        мимо = []
        for r in сделки:
            t, ц = метка(зн(r, "метка_выхода")), число(зн(r, "выход"))
            if t is None or ц is None:
                continue
            i = ряд.бар(t)
            if i is None:
                continue
            в, н = ряд.верх[i], ряд.низ[i]
            if в is None or н is None:
                continue
            сп = (ряд.спред[i] or 0.0) if ряд.есть_спред else 0.0
            доп = max(дов["допуск"], сп * дов["спредов"])
            if ц - в > доп + 1e-9 or н - ц > доп + 1e-9:
                мимо.append((t, ц, н, в))
        итог.проверка("цена выхода лежит внутри своего бара", not мимо,
                      "" if not мимо else "таких сделок %d" % len(мимо),
                      ["%s: выход %.5f при баре %.5f–%.5f"
                       % (сказать_время(t), ц, н, в) for t, ц, н, в in мимо])
    elif с["метка_выхода"]:
        итог.пробел("цена выхода", "в выгрузке нет цены выхода — П20 проверен наполовину")

    # --- 8. Неразрешимые бары: стоп и цель в одном баре (П13) ---------------
    if ряд and с["метка_входа"] and с["метка_выхода"] and с["стоп"] and с["цель"]:
        спорных, спорных_целью = 0, []
        for r in сделки:
            вх, вых = метка(зн(r, "метка_входа")), метка(зн(r, "метка_выхода"))
            ст, це = число(зн(r, "стоп")), число(зн(r, "цель"))
            лонг = сторона_лонг(зн(r, "сторона")) if с["сторона"] else None
            исход = str(зн(r, "исход") or "").upper()
            if None in (вх, вых, ст, це) or лонг is None:
                continue
            i, j = ряд.бар(вх), ряд.бар(вых)
            if i is None or j is None or j < i:
                continue
            for k in range(i, j + 1):
                в, н = ряд.верх[k], ряд.низ[k]
                if в is None or н is None:
                    continue
                задел_цель = (в >= це) if лонг else (н <= це)
                задел_стоп = (н <= ст) if лонг else (в >= ст)
                if задел_цель and задел_стоп:
                    спорных += 1
                    if "TP" in исход or "ЦЕЛ" in исход or "TAKE" in исход:
                        спорных_целью.append((сказать_время(ряд.метки[k]), исход))
                    break
        доля = 100.0 * спорных / len(сделки) if сделки else 0.0
        итог.проверка("бар, задевший и стоп, и цель, не записан целью",
                      not спорных_целью,
                      "спорных баров %d (%.1f %% сделок), из них записано целью %d"
                      % (спорных, доля, len(спорных_целью)),
                      ["%s, исход %s" % п for п in спорных_целью])

    # --- 9. Дубли (П35) -----------------------------------------------------
    # Ключ дубля обязан содержать время: без него одинаковые цены повторяются
    # на истории сами собой, и проверка превратилась бы в ложную тревогу.
    время_ключа = с["метка_сигнала"] and "метка_сигнала" or (
        с["метка_входа"] and "метка_входа" or None)
    ключи = ([время_ключа] if время_ключа else []) + \
            [к for к in ("сторона", "вход", "стоп") if с[к]]
    if not время_ключа:
        итог.пробел("дубли сделок",
                    "в выгрузке нет ни метки сигнала, ни метки входа — по одним "
                    "ценам дубль от повтора уровня не отличить")
    elif len(ключи) >= 3:
        # Внутри одного потока одинаковая сделка — дубль и беда (так нашлись
        # 1354 лишних позиции в разборе одного движка). Одна и та же сделка в
        # РАЗНЫХ потоках — вопрос к сетапу, а не поломка счёта: сторож её
        # называет, но не судит.
        с_потоком = ключи + (["поток"] if с["поток"] else [])
        счёт = Counter(tuple(str(зн(r, к)) for к in с_потоком) for r in сделки)
        дубли = [(к, n) for к, n in счёт.items() if n > 1]
        итог.проверка("дублей внутри потока нет", not дубли,
                      "" if not дубли else "ключей с повтором %d, лишних строк %d"
                      % (len(дубли), sum(n - 1 for _, n in дубли)),
                      ["%s — %d раз" % (" · ".join(к), n) for к, n in дубли])
        if с["поток"]:
            общий = Counter(tuple(str(зн(r, к)) for к in ключи) for r in сделки)
            вместе = [(к, n) for к, n in общий.items() if n > 1]
            if вместе:
                итог.пробел(
                    "одна сделка в разных потоках",
                    "таких совпадений %d (%d лишних строк): в бою это одна цена "
                    "и один рынок — решить, две это позиции или одна"
                    % (len(вместе), sum(n - 1 for _, n in вместе)))

    # --- 10. Итог в R сходится с ценами ------------------------------------
    if с["итог_r"] and с["вход"] and с["стоп"] and с["выход"] and с["сторона"]:
        разошлись = []
        for r in сделки:
            вх, ст, вых = (число(зн(r, "вход")), число(зн(r, "стоп")),
                           число(зн(r, "выход")))
            итог_r, лонг = число(зн(r, "итог_r")), сторона_лонг(зн(r, "сторона"))
            if None in (вх, ст, вых, итог_r) or лонг is None:
                continue
            риск = abs(вх - ст)
            if риск < 1e-9:
                continue
            свой = ((вых - вх) if лонг else (вх - вых)) / риск
            if abs(свой - итог_r) > 0.02:
                разошлись.append((итог_r, свой))
        итог.проверка("итог в R сходится с ценами входа, выхода и стопа",
                      not разошлись,
                      "" if not разошлись else "таких сделок %d" % len(разошлись),
                      ["в выгрузке %.3f R, по ценам %.3f R" % п for п in разошлись])
    else:
        итог.пробел("итог в R против цен",
                    "нет цены выхода или итога в R — цепочку чисел не замкнуть")

    # --- 11. Подозрительная гладкость исходов -------------------------------
    if с["итог_r"]:
        значения = [число(зн(r, "итог_r")) for r in сделки]
        значения = [v for v in значения if v is not None]
        if значения:
            нулей = sum(1 for v in значения if abs(v) < 1e-9)
            ровных = sum(1 for v in значения if abs(v + 1.0) < 1e-9)
            повтор = Counter(round(x, 4) for x in значения).most_common(1)[0]
            print("             итоги: сделок %d, ровных нулей %d (%.1f %%), ровно "
                  "−1.00 R %d (%.1f %%), самое частое значение %.4f — %d раз"
                  % (len(значения), нулей, 100.0 * нулей / len(значения),
                     ровных, 100.0 * ровных / len(значения), повтор[0], повтор[1]))
            if ровных and ровных >= 0.15 * len(значения):
                итог.пробел("стопы ровно −1.00 R",
                            "их %d (%.1f %%): проскальзывания в этом прогоне нет "
                            "вовсе — цену допущения назвать числом (П28)"
                            % (ровных, 100.0 * ровных / len(значения)))

    # --- 12. Объём у брокера (П30) -----------------------------------------
    if с["объём"] and (дов["шаг_лота"] or дов["мин_лот"]):
        не_кратен, мелких = [], []
        for r in сделки:
            v = число(зн(r, "объём"))
            if v is None:
                continue
            if дов["шаг_лота"]:
                шагов = v / дов["шаг_лота"]
                if abs(шагов - round(шагов)) > 1e-6:
                    не_кратен.append(v)
            if дов["мин_лот"] and v < дов["мин_лот"] - 1e-9:
                мелких.append(v)
        if дов["шаг_лота"]:
            итог.проверка("объём кратен шагу лота", not не_кратен,
                          "" if not не_кратен else "таких сделок %d" % len(не_кратен))
        if дов["мин_лот"]:
            итог.проверка("объём не ниже наименьшего лота", not мелких,
                          "" if not мелких else "таких сделок %d" % len(мелких))
    elif not с["объём"]:
        итог.пробел("объём", "в выгрузке нет объёма — П30 не проверить")

    # --- 13. Сколько позиций стояло разом ----------------------------------
    if с["метка_входа"] and с["метка_выхода"]:
        события = []
        for r in сделки:
            вх, вых = метка(зн(r, "метка_входа")), метка(зн(r, "метка_выхода"))
            if вх is None or вых is None:
                continue
            события.append((вх, 1))
            события.append((вых, -1))
        события.sort()
        сейчас = пик = 0
        когда = None
        for t, d in события:
            сейчас += d
            if сейчас > пик:
                пик, когда = сейчас, t
        print("             разом открытых позиций: больше всего %d, %s"
              % (пик, сказать_время(когда)))


