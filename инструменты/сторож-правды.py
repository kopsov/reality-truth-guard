def найти_столбцы(заголовки, словарь, карта):
    найдено, низ = {}, {h.lower(): h for h in заголовки}
    for ключ, варианты in словарь.items():
        если_задан = карта.get(ключ)
        if если_задан:
            найдено[ключ] = если_задан if если_задан in заголовки else None
            continue
        for в in варианты:
            if в in заголовки:
                найдено[ключ] = в
                break
            if в.lower() in низ:
                найдено[ключ] = низ[в.lower()]
                break
        else:
            найдено[ключ] = None
    return найдено


def читать(путь):
    with open(путь, encoding="utf-8-sig", newline="") as ф:
        проба = ф.read(8192)
        ф.seek(0)
        try:
            диалект = csv.Sniffer().sniff(проба, delimiters=",;\t")
        except csv.Error:
            диалект = csv.excel
        чтец = csv.DictReader(ф, dialect=диалект)
        return чтец.fieldnames or [], list(чтец)


