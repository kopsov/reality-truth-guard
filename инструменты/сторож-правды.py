_ФОРМАТЫ = ("%Y-%m-%dT%H:%M:%SZ", "%Y-%m-%dT%H:%M:%S", "%Y-%m-%d %H:%M:%S",
            "%Y-%m-%d %H:%M", "%Y.%m.%d %H:%M:%S", "%Y.%m.%d %H:%M")


def метка(значение):
    """Метка времени в секундах. Понимает число и обычные записи даты."""
    if значение in ("", None):
        return None
    s = str(значение).strip()
    if not s:
        return None
    try:
        ч = float(s)
        return int(ч / 1000) if ч > 1e11 else int(ч)
    except ValueError:
        pass
    for ф in _ФОРМАТЫ:
        try:
            return int(datetime.strptime(s, ф).replace(tzinfo=timezone.utc).timestamp())
        except ValueError:
            continue
    return None


def число(значение):
    if значение in ("", None):
        return None
    try:
        return float(str(значение).replace(",", "."))
    except ValueError:
        return None


def сторона_лонг(значение):
    """1, buy, long, покупка — лонг; -1, sell, short, продажа — шорт."""
    if значение in ("", None):
        return None
    s = str(значение).strip().lower()
    if s in ("1", "1.0", "buy", "long", "b", "покупка", "лонг", "+1"):
        return True
    if s in ("-1", "-1.0", "sell", "short", "s", "продажа", "шорт", "0"):
        return False
    return None


def сказать_время(ts):
    return datetime.fromtimestamp(ts, timezone.utc).strftime("%Y-%m-%d %H:%M") if ts else "—"


def _воскресенье(год, месяц, номер):
    д = datetime(год, месяц, 1, tzinfo=timezone.utc)
    сдвиг = (6 - д.weekday()) % 7
    return д.replace(day=1 + сдвиг + 7 * (номер - 1))


_БРОКЕР = {}


def сдвиг_еет_сша(ts):
    """Часы, на которые сервер брокера опережает Гринвич.

    Зимой UTC+2, летом UTC+3; переходы по американским правилам. Правило
    снято с часовых свечей терминала одного конкретного брокера за 2022–2026 и верно
    для него. Другому брокеру его подставлять нельзя — надо снять заново.
    """
    год = datetime.fromtimestamp(ts, timezone.utc).year
    к = _БРОКЕР.get(год)
    if к is None:
        в, о = _воскресенье(год, 3, 2), _воскресенье(год, 11, 1)
        к = _БРОКЕР[год] = (int(в.replace(hour=7).timestamp()),
                            int(о.replace(hour=6).timestamp()))
    return 3 if к[0] <= ts < к[1] else 2


