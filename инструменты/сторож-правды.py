class Итог:
    def __init__(self, примеров):
        self.бед = []
        self.пробелы = []
        self.примеров = примеров

    def проверка(self, имя, хорошо, подробно="", примеры=()):
        print("  %-8s %s%s" % ("сходится" if хорошо else "БЕДА", имя,
                               ("   " + подробно) if подробно else ""))
        if not хорошо:
            self.бед.append(имя)
            for строка in list(примеры)[:self.примеров]:
                print("             · %s" % строка)

    def пробел(self, имя, почему):
        print("  %-8s %s   %s" % ("не знаю", имя, почему))
        self.пробелы.append((имя, почему))


