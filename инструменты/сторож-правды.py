class Ряд:
    def __init__(self, путь, карта, точка=None):
        заголовки, строки = читать(путь)
        с = найти_столбцы(заголовки, ИМЕНА_РЯДА, карта)
        для = lambda r, к: r.get(с[к]) if с.get(к) else None
        # Выгрузка MetaTrader держит дату и время порознь — склеиваем.
        порознь = bool(с.get("дата")) and bool(с.get("время"))
        self.метки, self.верх, self.низ = [], [], []
        self.откр, self.закр, self.спред = [], [], []
        self.точка = точка
        for r in строки:
            if порознь:
                d, тм = для(r, "дата"), для(r, "время")
                t = метка("%s %s" % (str(d).replace(".", "-").strip(), str(тм).strip()))
            else:
                t = метка(для(r, "время"))
            if t is None:
                continue
            self.метки.append(t)
            self.откр.append(число(для(r, "откр")))
            self.верх.append(число(для(r, "верх")))
            self.низ.append(число(для(r, "низ")))
            self.закр.append(число(для(r, "закр")))
            сп = число(для(r, "спред"))
            self.спред.append(сп * точка if (сп is not None and точка) else сп)
        self.есть_спред = с.get("спред") is not None
        self.спред_в_пунктах = False
        # У выгрузки MetaTrader спред записан пунктами, а не ценой. Не назван
        # размер пункта — спред на два порядка больше правды, и допуск по нему
        # пропустил бы любую цену. Такой спред лучше не иметь вовсе.
        if self.есть_спред and not точка:
            есть = [s for s in self.спред if s is not None]
            целых = sum(1 for s in есть if abs(s - round(s)) < 1e-9)
            if есть and целых > 0.9 * len(есть) and max(есть) >= 5:
                self.есть_спред = False
                self.спред_в_пунктах = True
        self.место = {t: i for i, t in enumerate(self.метки)}
        self.шаг = Counter(b - a for a, b in zip(self.метки, self.метки[1:])).most_common(1)
        self.шаг = self.шаг[0][0] if self.шаг else None

    def __len__(self):
        return len(self.метки)

    def бар(self, ts):
        """Бар, внутри которого лежит метка. Ищется по сетке шага ряда."""
        i = self.место.get(ts)
        if i is not None:
            return i
        if not self.шаг:
            return None
        return self.место.get(ts - (ts % self.шаг))


